import { describe, expect, it } from "vitest";

describe("Chat Media & Links Extractor", () => {
  it("extracts direct image URLs and hosted images from message bodies", () => {
    const bodies = [
      "Hey check this photo https://images.unsplash.com/photo-1534528741775-53994a69daeb?w=500 it's great",
      "Look at this screenshot https://i.ibb.co/abc123/screenshot.png and tell me",
      "Regular text with no media",
      "Another one: https://cdn.example.com/banner.webp?quality=80",
    ];

    const imageRegex = /(https?:\/\/[^\s]+?\.(?:png|jpg|jpeg|gif|webp)(?:\?[^\s]*)?)/gi;
    const hostedImageRegex = /(https?:\/\/(?:images\.unsplash\.com|i\.ibb\.co|res\.cloudinary\.com)[^\s]+)/gi;

    const extracted: string[] = [];
    bodies.forEach((b) => {
      const matches = b.match(imageRegex) || b.match(hostedImageRegex);
      if (matches) {
        extracted.push(...matches);
      }
    });

    expect(extracted).toHaveLength(3);
    expect(extracted[0]).toContain("unsplash.com");
    expect(extracted[1]).toContain("i.ibb.co");
    expect(extracted[2]).toContain("banner.webp");
  });

  it("extracts hyperlinks from messages and skips pure image URLs", () => {
    const body =
      "Visit https://campusloop.space and read the docs at https://github.com/SH20RAJ/campusloop also see https://example.com/pic.jpg";
    const urlRegex = /(https?:\/\/[^\s]+)/gi;

    const matches = body.match(urlRegex) || [];
    const webLinks = matches.filter((url) => !/\.(png|jpg|jpeg|gif|webp)(\?.*)?$/i.test(url));

    expect(webLinks).toHaveLength(2);
    expect(webLinks[0]).toBe("https://campusloop.space");
    expect(webLinks[1]).toBe("https://github.com/SH20RAJ/campusloop");
  });

  it("correctly determines host domain from full URL", () => {
    const url1 = "https://www.campusloop.space/app/chat";
    const parsed1 = new URL(url1);
    expect(parsed1.hostname.replace(/^www\./, "")).toBe("campusloop.space");

    const url2 = "https://github.com/SH20RAJ/campusloop";
    const parsed2 = new URL(url2);
    expect(parsed2.hostname.replace(/^www\./, "")).toBe("github.com");
  });

  it("correctly synthesizes group participant object from conversation", () => {
    const groupConv = {
      id: "conv_group_12345678",
      title: "ECE 2026 Study Pod",
      avatarUrl: null,
      type: "STUDY_POD",
      participants: [
        { user: { id: "u1", displayName: "Student One", username: "one" } },
        { user: { id: "u2", displayName: "Student Two", username: "two" } },
      ],
    };

    const isGroup = groupConv.type !== "DIRECT";
    const synthesized = isGroup
      ? {
          id: groupConv.id,
          userId: groupConv.id,
          displayName: groupConv.title || "Campus Group",
          username: `grp_${groupConv.id.slice(0, 8)}`,
          avatarUrl: groupConv.avatarUrl || null,
          bio: `${groupConv.participants.length} campus members`,
          isGroup: true,
          category: groupConv.type,
          membersCount: groupConv.participants.length,
          participants: groupConv.participants.map((p) => p.user),
        }
      : null;

    expect(synthesized).not.toBeNull();
    expect(synthesized?.displayName).toBe("ECE 2026 Study Pod");
    expect(synthesized?.isGroup).toBe(true);
    expect(synthesized?.membersCount).toBe(2);
    expect(synthesized?.participants).toHaveLength(2);
  });

  it("accurately parses marketplace inquiries from chat message bodies", async () => {
    const { parseMarketplaceInquiry } = await import(
      "@/components/chat/product-message-card"
    );

    // Standard automated inquiry generated by marketplace "Contact Seller"
    const inquiry1 =
      'Hi @nikhil_mehta092, is "Hero Sprint 21-Speed Gear Bicycle with Dual Disc Brakes" (₹2,800) still available?';
    const parsed1 = parseMarketplaceInquiry(inquiry1);

    expect(parsed1).not.toBeNull();
    expect(parsed1?.title).toBe(
      "Hero Sprint 21-Speed Gear Bicycle with Dual Disc Brakes"
    );
    expect(parsed1?.price).toBe("₹2,800");
    expect(parsed1?.isAvailableQuestion).toBe(true);

    // Variation with Rs. currency
    const inquiry2 =
      'Hello @sh20raj, is "Engineering Mathematics - III by B.S. Grewal" (Rs. 450) still available?';
    const parsed2 = parseMarketplaceInquiry(inquiry2);

    expect(parsed2).not.toBeNull();
    expect(parsed2?.title).toBe(
      "Engineering Mathematics - III by B.S. Grewal"
    );
    expect(parsed2?.price).toBe("₹450");
    expect(parsed2?.isAvailableQuestion).toBe(true);

    // Quoted item without the automated question wrapper
    const inquiry3 =
      'Check this out: "Casio FX-991EX Scientific Calculator" (₹1,200)';
    const parsed3 = parseMarketplaceInquiry(inquiry3);

    expect(parsed3).not.toBeNull();
    expect(parsed3?.title).toBe("Casio FX-991EX Scientific Calculator");
    expect(parsed3?.price).toBe("₹1,200");
    expect(parsed3?.isAvailableQuestion).toBe(false);

    // Regular conversation without product inquiries returns null
    const normalText = "Hey are you coming to the lab today?";
    expect(parseMarketplaceInquiry(normalText)).toBeNull();
  });
});
